// Puts the plugin's stylesheet together.
//
// Obsidian loads one stylesheet per plugin: styles.css next to main.js. The
// plugin's styles are written as several files in src/styles, one for what
// the screens share and one for each screen, so that people working on
// different screens never change the same file. The build joins them, always
// in the same order, into styles.css at the top of the repository. That file
// is generated: it is not kept in git and must not be edited by hand.

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

/** The folder the parts are in, relative to the repository root. */
export const STYLES_DIR = 'src/styles';

/** The generated stylesheet, relative to the repository root. */
export const STYLES_OUTPUT = 'styles.css';

/**
 * The parts of the stylesheet, in the order they are joined. The order is
 * fixed, so that the same sources always give the same stylesheet: what is
 * shared comes first, then one file for each screen.
 */
export const STYLE_FILES = Object.freeze([
  'base.css',
  'binder.css',
  'corkboard.css',
  'progress.css',
  'planner.css',
  'timeline.css',
  'outliner.css',
  'schemes.css',
  'modes.css',
]);

const BANNER = `/*
 * Spellbook, a novel writer.
 * This file is generated by the build from the files in ${STYLES_DIR}. Do not edit it by hand.
 */
`;

/**
 * Join the parts into one stylesheet.
 *
 * @param {ReadonlyArray<{ name: string, text: string }>} parts the files, in order
 * @returns {string}
 */
export function joinStyles(parts) {
  const sections = parts.map((part) => `/* ===== ${STYLES_DIR}/${part.name} ===== */\n\n${part.text.trim()}\n`);
  return [BANNER, ...sections].join('\n');
}

/**
 * Read the parts and join them.
 *
 * @param {string} repoRoot absolute path of the plugin repository
 * @returns {string} the whole stylesheet
 */
export function readStyles(repoRoot) {
  return joinStyles(
    STYLE_FILES.map((name) => ({ name, text: readFileSync(path.join(repoRoot, STYLES_DIR, name), 'utf8') })),
  );
}

/**
 * Write the generated stylesheet, unless it already says exactly that.
 *
 * @param {string} repoRoot absolute path of the plugin repository
 * @returns {string} the path that was written
 */
export function writeStyles(repoRoot) {
  const output = path.join(repoRoot, STYLES_OUTPUT);
  const text = readStyles(repoRoot);
  let current = null;
  try {
    current = readFileSync(output, 'utf8');
  } catch {
    current = null;
  }
  if (current !== text) writeFileSync(output, text, 'utf8');
  return output;
}
